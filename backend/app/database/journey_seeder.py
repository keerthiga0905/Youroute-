def seed_journey_destinations(db: Session):
    """
    Seeds curated destinations with verified coordinates, authentic images,
    rich metadata, and mood relationships.
    """
    if db.query(Destination).count() > 0:
        return

    print(f"[Journey Seeder]: Seeding {len(DESTINATIONS_DATA)} curated destinations...")
    for item in DESTINATIONS_DATA:
        gallery_items = item.pop("gallery", [])
        
        dest = Destination(
            name=item["name"],
            slug=item["slug"],
            country=item["country"],
            state=item.get("state"),
            city=item["city"],
            travel_scope=item["travel_scope"],
            category=item["category"],
            sub_category=item.get("sub_category"),
            supported_moods=item["supported_moods"],
            description=item["description"],
            why_recommended=item.get("why_recommended"),
            latitude=item["latitude"],
            longitude=item["longitude"],
            hero_image_url=item["hero_image_url"],
            best_season=item.get("best_season"),
            typical_duration=item.get("typical_duration"),
            approx_budget_tier=item.get("approx_budget_tier", "Moderate"),
            approx_cost_per_day_inr=item.get("approx_cost_per_day_inr"),
            opening_hours=item.get("opening_hours"),
            accessibility_info=item.get("accessibility_info"),
            official_website_url=item.get("official_website_url"),
            source_attribution=item.get("source_attribution"),
            is_popular=item.get("is_popular", False),
            is_featured=item.get("is_featured", False),
            is_hidden_gem=item.get("is_hidden_gem", False)
        )
        db.add(dest)
        db.flush() # Flush to get dest.id

        # Add primary image
        primary_img = DestinationImage(
            destination_id=dest.id,
            image_url=dest.hero_image_url,
            caption=f"Panoramic view of {dest.name}",
            attribution=dest.source_attribution or "Tourism Archive",
            is_primary=True
        )
        db.add(primary_img)

        # Add gallery images
        for g in gallery_items:
            sec_img = DestinationImage(
                destination_id=dest.id,
                image_url=g["image_url"],
                caption=g.get("caption", dest.name),
                attribution="Curated Travel Archive",
                is_primary=False
            )
            db.add(sec_img)

    db.commit()
    print("[Journey Seeder]: Successfully seeded all curated travel destinations.")

def run_journey_seeder():
    from app.core.database import engine, Base
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        seed_journey_destinations(db)
    except Exception as e:
        db.rollback()
        print(f"[Journey Seeder Error]: {e}")
    finally:
        db.close()

if __name__ == "__main__":
    run_journey_seeder()
